--[[
	InstallRodCast.lua - GENERATED by tools/rod-cast/build/build_installer.py.
	Edit tools/rod-cast sources and rebuild; don't edit this file.

	Opt-in Studio installer: pressing the big button casts every eligible rod
	together, immediately, and the rods visibly dip toward the water.
	Requires the aquarium; works with or without the fish-variants install
	(install variants FIRST if you want both: the variants installer refuses
	a RodFishingSystem it doesn't recognize).
	HOW TO RUN: stop Play, paste this whole file into the Command Bar (Edit
	mode), press Enter. It never runs automatically.

	Checks first, changes nothing on failure:
	  * ServerStorage.RodCastBackup doesn't exist
	  * exactly one Script RodFishingSystem (ServerScriptService/Workspace)
	    matching the reviewed variants+aquarium or aquarium-only version
	  * exactly one LocalScript RodFishingClient matching the reviewed original
	In one undo step ("Install RodCast") it backs both up to
	ServerStorage.RodCastBackup (Target + disabled Before/After copies) and
	patches them. UninstallRodCast.lua restores the Before sources.
]]

local ChangeHistoryService = game:GetService("ChangeHistoryService")
local ReplicatedFirst = game:GetService("ReplicatedFirst")
local ServerScriptService = game:GetService("ServerScriptService")
local ServerStorage = game:GetService("ServerStorage")
local StarterGui = game:GetService("StarterGui")
local StarterPlayer = game:GetService("StarterPlayer")

-- { name, localScript, candidates = { { label, base, patched } } }
local TARGETS = --[[@TARGETS]]

local TAG = "RodCastOwned"

local function fail(msg)
	warn("[InstallRodCast] " .. msg .. " - nothing changed.")
end

local function normalize(s)
	s = s:gsub("\r", "")
	s = s:gsub("[ \t]+\n", "\n")
	s = s:gsub("%s+$", "")
	return s
end

if ServerStorage:FindFirstChild("RodCastBackup") then
	return fail("ServerStorage.RodCastBackup already exists (run UninstallRodCast.lua first)")
end

local function find(name, isLocal)
	local containers = if isLocal
		then { StarterPlayer, StarterGui, ReplicatedFirst }
		else { ServerScriptService, workspace }
	local found = {}
	for _, container in ipairs(containers) do
		for _, d in ipairs(container:GetDescendants()) do
			if d.Name == name and d:IsA("Script") and (d:IsA("LocalScript") == isLocal) then
				table.insert(found, d)
			end
		end
	end
	return found
end

local changes = {}
for _, t in ipairs(TARGETS) do
	local found = find(t.name, t.localScript)
	if #found ~= 1 then
		return fail(string.format("expected exactly 1 %s named %s, found %d", if t.localScript then "LocalScript" else "Script", t.name, #found))
	end
	local target = found[1]
	local current = normalize(target.Source)
	local match
	for _, c in ipairs(t.candidates) do
		if current == normalize(c.base) then
			match = c
			break
		end
	end
	if not match then
		return fail(target:GetFullName() .. " doesn't match any reviewed base (aquarium installed? already patched?)")
	end
	table.insert(changes, { target = target, after = match.patched, label = t.name .. " (" .. match.label .. ")" })
end

local recording
local ok = pcall(function()
	recording = ChangeHistoryService:TryBeginRecording("Install RodCast")
end)
if not ok or not recording then
	recording = nil
	pcall(function()
		ChangeHistoryService:SetWaypoint("Before Install RodCast")
	end)
end

local originals, backup = {}, nil
local built, buildErr = pcall(function()
	backup = Instance.new("Folder")
	backup.Name = "RodCastBackup"
	backup:SetAttribute(TAG, true)
	for i, change in ipairs(changes) do
		originals[i] = change.target.Source
		local entry = Instance.new("Folder")
		entry.Name = string.format("%02d_%s", i, change.target.Name)
		local targetValue = Instance.new("ObjectValue")
		targetValue.Name = "Target"
		targetValue.Value = change.target
		targetValue.Parent = entry
		local before = change.target:Clone()
		before.Name = "Before"
		before.Enabled = false
		before.Parent = entry
		change.target.Source = change.after
		local after = change.target:Clone()
		after.Name = "After"
		after.Enabled = false
		after.Parent = entry
		entry.Parent = backup
	end
	backup.Parent = ServerStorage
end)

if not built then
	for i, change in ipairs(changes) do
		if originals[i] then
			pcall(function()
				change.target.Source = originals[i]
			end)
		end
	end
	if backup then
		pcall(function()
			backup:Destroy()
		end)
	end
end

if recording then
	ChangeHistoryService:FinishRecording(
		recording,
		if built then Enum.FinishRecordingOperation.Commit else Enum.FinishRecordingOperation.Cancel
	)
elseif built then
	pcall(function()
		ChangeHistoryService:SetWaypoint("Install RodCast")
	end)
end

if not built then
	return warn("[InstallRodCast] Failed and rolled back: " .. tostring(buildErr))
end
print("[InstallRodCast] Installed:")
for _, change in ipairs(changes) do
	print("  patched " .. change.target:GetFullName() .. " from " .. change.label)
end
print("  If rods tilt UP instead of down on cast, flip CAST_DIP_DEG in RodFishingClient.")
