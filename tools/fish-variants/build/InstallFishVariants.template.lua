--[[
	InstallFishVariants.lua - GENERATED by tools/fish-variants/build/build_installer.py.
	Edit tools/fish-variants sources and rebuild; don't edit this file.

	Opt-in Studio installer for rare Silver/Gold fish variants.
	REQUIRES the aquarium to be installed first (RodFishingSystem is patched on
	top of the aquarium version). Independent of the fish-jump install.
	HOW TO RUN: stop Play, paste this whole file into the Command Bar (Edit
	mode), press Enter. It never runs automatically.

	Checks everything first and changes nothing if any check fails:
	  * none of its own objects already exist
	  * exactly one Script each named FishSpawner, RodFishingSystem,
	    NetLiftScript, GrinderProcessor, TruckSystem, CustomerSystem (searched
	    in ServerScriptService and Workspace), each matching its reviewed base
	    source (RodFishingSystem: the aquarium-patched version)
	  * the installed aquarium modules are the reviewed v1 (upgraded to v1.1,
	    which carries a fish's Variant through the tank) or already v1.1
	Then, in one undo step ("Install FishVariants"):
	  * backs up every script/module it changes to ServerStorage.FishVariantsBackup
	    (Target ObjectValue + disabled Before/After copies each)
	  * patches the six scripts and upgrades the aquarium modules
	  * adds ReplicatedStorage.FishVariants, ReplicatedStorage.FishVariantVisuals,
	    ServerScriptService.FishPayout (returns nil: nothing is paid)
	Added objects carry FishVariantsOwned = true. UninstallFishVariants.lua
	restores every Before source and removes only tagged objects.
]]

local ALLOW_SOURCE_MISMATCH = false

local ChangeHistoryService = game:GetService("ChangeHistoryService")
local ReplicatedStorage = game:GetService("ReplicatedStorage")
local ServerScriptService = game:GetService("ServerScriptService")
local ServerStorage = game:GetService("ServerStorage")
local StarterPlayer = game:GetService("StarterPlayer")

-- { name, base, patched } for each live Script
local SCRIPTS = --[[@SCRIPTS]]
-- { key, v1, v11 } for each installed aquarium module
local AQUARIUM = --[[@AQUARIUM]]
local MOD_VARIANTS = --[[@VARIANTS]]
local MOD_VISUALS = --[[@VISUALS]]
local MOD_PAYOUT = --[[@PAYOUT]]

local TAG = "FishVariantsOwned"

local function fail(msg)
	warn("[InstallFishVariants] " .. msg .. " - nothing changed.")
end

local function normalize(s)
	s = s:gsub("\r", "")
	s = s:gsub("[ \t]+\n", "\n")
	s = s:gsub("%s+$", "")
	return s
end

------------------------------------------------------------ checks (read-only)

for _, existing in ipairs({
	ReplicatedStorage:FindFirstChild("FishVariants"),
	ReplicatedStorage:FindFirstChild("FishVariantVisuals"),
	ServerScriptService:FindFirstChild("FishPayout"),
	ServerStorage:FindFirstChild("FishVariantsBackup"),
}) do
	if existing then
		return fail(existing:GetFullName() .. " already exists (run UninstallFishVariants.lua first)")
	end
end

local function findScript(name)
	local found = {}
	for _, container in ipairs({ ServerScriptService, workspace }) do
		for _, d in ipairs(container:GetDescendants()) do
			if d.Name == name and d:IsA("Script") and not d:IsA("LocalScript") then
				table.insert(found, d)
			end
		end
	end
	return found
end

local changes = {} -- { target, before, after, label }
for _, entry in ipairs(SCRIPTS) do
	local found = findScript(entry.name)
	if #found ~= 1 then
		return fail(string.format("expected exactly 1 Script named %s, found %d", entry.name, #found))
	end
	local target = found[1]
	if normalize(target.Source) ~= normalize(entry.base) and not ALLOW_SOURCE_MISMATCH then
		local hint = if entry.name == "RodFishingSystem"
			then " (is the aquarium installed? this patch builds on the aquarium version)"
			else ""
		return fail(target:GetFullName() .. " source differs from the reviewed base" .. hint)
	end
	table.insert(changes, { target = target, after = entry.patched, label = entry.name })
end

local aquariumFolder = ReplicatedStorage:FindFirstChild("AquariumCycle")
local starterScripts = StarterPlayer:FindFirstChildOfClass("StarterPlayerScripts")
local aquariumTargets = {
	Config = aquariumFolder and aquariumFolder:FindFirstChild("Config"),
	SharedTank = aquariumFolder and aquariumFolder:FindFirstChild("SharedTank"),
	AquariumCycleServer = ServerScriptService:FindFirstChild("AquariumCycleServer"),
	AquariumTankClient = starterScripts and starterScripts:FindFirstChild("AquariumTankClient"),
}
local upgraded, alreadyCurrent = 0, 0
for _, entry in ipairs(AQUARIUM) do
	local target = aquariumTargets[entry.key]
	if not (target and target:IsA("LuaSourceContainer")) then
		return fail("aquarium module " .. entry.key .. " not found (install the aquarium first)")
	end
	local current = normalize(target.Source)
	if current == normalize(entry.v11) then
		alreadyCurrent += 1
	elseif current == normalize(entry.v1) then
		table.insert(changes, { target = target, after = entry.v11, label = "aquarium " .. entry.key })
		upgraded += 1
	else
		return fail(target:GetFullName() .. " is neither the reviewed aquarium v1 nor v1.1")
	end
end

------------------------------------------------------------ install

local recording
local ok = pcall(function()
	recording = ChangeHistoryService:TryBeginRecording("Install FishVariants")
end)
if not ok or not recording then
	recording = nil
	pcall(function()
		ChangeHistoryService:SetWaypoint("Before Install FishVariants")
	end)
end

local originals = {}
local created = {}

local function copyOf(source, name)
	local c = source:Clone()
	c.Name = name
	if c:IsA("Script") or c:IsA("LocalScript") then
		c.Enabled = false
	end
	return c
end

local built, buildErr = pcall(function()
	local backup = Instance.new("Folder")
	backup.Name = "FishVariantsBackup"
	backup:SetAttribute(TAG, true)
	table.insert(created, backup)
	for i, change in ipairs(changes) do
		originals[i] = change.target.Source
		local entry = Instance.new("Folder")
		entry.Name = string.format("%02d_%s", i, change.label:gsub("%W", "_"))
		entry:SetAttribute("TargetPath", change.target:GetFullName())
		local targetValue = Instance.new("ObjectValue")
		targetValue.Name = "Target"
		targetValue.Value = change.target
		targetValue.Parent = entry
		copyOf(change.target, "Before").Parent = entry
		change.target.Source = change.after
		copyOf(change.target, "After").Parent = entry
		entry.Parent = backup
	end
	backup.Parent = ServerStorage

	local function addModule(name, source, parent)
		local m = Instance.new("ModuleScript")
		m.Name = name
		m.Source = source
		m:SetAttribute(TAG, true)
		table.insert(created, m)
		m.Parent = parent
	end
	addModule("FishVariants", MOD_VARIANTS, ReplicatedStorage)
	addModule("FishVariantVisuals", MOD_VISUALS, ReplicatedStorage)
	addModule("FishPayout", MOD_PAYOUT, ServerScriptService)
end)

if not built then
	for i, change in ipairs(changes) do
		if originals[i] then
			pcall(function()
				change.target.Source = originals[i]
			end)
		end
	end
	for i = #created, 1, -1 do
		pcall(function()
			created[i]:Destroy()
		end)
	end
end

if recording then
	ChangeHistoryService:FinishRecording(
		recording,
		if built then Enum.FinishRecordingOperation.Commit else Enum.FinishRecordingOperation.Cancel
	)
elseif built then
	pcall(function()
		ChangeHistoryService:SetWaypoint("Install FishVariants")
	end)
end

if not built then
	return warn("[InstallFishVariants] Failed and rolled back: " .. tostring(buildErr))
end
print("[InstallFishVariants] Installed:")
for _, change in ipairs(changes) do
	print("  patched " .. change.target:GetFullName())
end
print(string.format("  aquarium modules: %d upgraded to v1.1, %d already v1.1", upgraded, alreadyCurrent))
print("  added   ReplicatedStorage.FishVariants, ReplicatedStorage.FishVariantVisuals, ServerScriptService.FishPayout")
print("  money   none: ServerScriptService.FishPayout returns nil until a real currency is connected")
