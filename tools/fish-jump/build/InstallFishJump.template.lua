--[[
	InstallFishJump.lua - GENERATED by tools/fish-jump/build/build_installer.py.
	Edit tools/fish-jump sources and rebuild; don't edit this file.

	Opt-in Studio installer: river fish occasionally jump out of the water
	(client visuals only). Independent of the aquarium install; either order.
	HOW TO RUN: stop Play, paste this whole file into the Command Bar (Edit
	mode), press Enter. It never runs automatically.

	Checks first and changes nothing if any fails:
	  * ReplicatedStorage.FishJump and ServerStorage.FishJumpBackup don't exist
	  * exactly one LocalScript named FishSwimClient (searched in StarterPlayer,
	    StarterGui, ReplicatedFirst) whose source matches the reviewed original
	Then, in one undo step ("Install FishJump"):
	  1. backs up FishSwimClient to ServerStorage.FishJumpBackup
	     (disabled copies of the original and the patched script)
	  2. replaces FishSwimClient.Source with the patched version
	  3. adds ReplicatedStorage.FishJump (ModuleScript)
	Added objects carry FishJumpOwned = true; UninstallFishJump.lua removes
	only those and restores the original source.

	Tuning / kill switch, live, no reinstall: attributes on
	Workspace.SwimmingFish: JumpEnabled (bool), JumpChance (0..1),
	JumpHeightScale (multiplier). Defaults are in the FishJump module.
]]

local ALLOW_SOURCE_MISMATCH = false

local ChangeHistoryService = game:GetService("ChangeHistoryService")
local ReplicatedFirst = game:GetService("ReplicatedFirst")
local ReplicatedStorage = game:GetService("ReplicatedStorage")
local ServerStorage = game:GetService("ServerStorage")
local StarterGui = game:GetService("StarterGui")
local StarterPlayer = game:GetService("StarterPlayer")

local ORIGINAL = --[[@ORIGINAL]]
local PATCHED = --[[@PATCHED]]
local MODULE = --[[@MODULE]]

local TAG = "FishJumpOwned"

local function fail(msg)
	warn("[InstallFishJump] " .. msg .. " - nothing changed.")
end

local function normalize(s)
	s = s:gsub("\r", "")
	s = s:gsub("[ \t]+\n", "\n")
	s = s:gsub("%s+$", "")
	return s
end

if ReplicatedStorage:FindFirstChild("FishJump") or ServerStorage:FindFirstChild("FishJumpBackup") then
	return fail("already installed (run UninstallFishJump.lua first)")
end

local found = {}
for _, container in ipairs({ StarterPlayer, StarterGui, ReplicatedFirst }) do
	for _, d in ipairs(container:GetDescendants()) do
		if d.Name == "FishSwimClient" and d:IsA("LocalScript") then
			table.insert(found, d)
		end
	end
end
if #found ~= 1 then
	return fail(string.format("expected exactly 1 LocalScript named FishSwimClient, found %d", #found))
end
local client = found[1]
local sourceMatches = normalize(client.Source) == normalize(ORIGINAL)
if not sourceMatches and not ALLOW_SOURCE_MISMATCH then
	return fail(
		client:GetFullName()
			.. " source differs from the reviewed original (tools/fish-jump/studio/FishSwimClient.original.lua)."
			.. " Send the current source for a re-patch, or set ALLOW_SOURCE_MISMATCH after review"
	)
end

local river = workspace:FindFirstChild("SwimmingFish")
if not (river and type(river:GetAttribute("MinZ")) == "number" and type(river:GetAttribute("MaxZ")) == "number") then
	warn("[InstallFishJump] Workspace.SwimmingFish MinZ/MaxZ not found: fish won't jump until they exist.")
end

local recording
local ok = pcall(function()
	recording = ChangeHistoryService:TryBeginRecording("Install FishJump")
end)
if not ok or not recording then
	recording = nil
	pcall(function()
		ChangeHistoryService:SetWaypoint("Before Install FishJump")
	end)
end

local originalSource = client.Source
local created = {}

local built, buildErr = pcall(function()
	local backup = Instance.new("Folder")
	backup.Name = "FishJumpBackup"
	backup:SetAttribute(TAG, true)
	backup:SetAttribute("OriginalPath", client:GetFullName())
	table.insert(created, backup)
	local originalCopy = client:Clone()
	originalCopy.Name = "FishSwimClient_original"
	originalCopy.Enabled = false
	originalCopy.Parent = backup
	local target = Instance.new("ObjectValue")
	target.Name = "Target"
	target.Value = client
	target.Parent = backup
	backup.Parent = ServerStorage

	client.Source = PATCHED
	local patchedCopy = client:Clone()
	patchedCopy.Name = "FishSwimClient_patched"
	patchedCopy.Enabled = false
	patchedCopy.Parent = backup

	local module = Instance.new("ModuleScript")
	module.Name = "FishJump"
	module.Source = MODULE
	module:SetAttribute(TAG, true)
	table.insert(created, module)
	module.Parent = ReplicatedStorage
end)

if not built then
	pcall(function()
		client.Source = originalSource
	end)
	for i = #created, 1, -1 do
		pcall(function()
			created[i]:Destroy()
		end)
	end
end

if recording then
	ChangeHistoryService:FinishRecording(
		recording,
		if built then Enum.FinishRecordingOperation.Commit else Enum.FinishRecordingOperation.Cancel
	)
elseif built then
	pcall(function()
		ChangeHistoryService:SetWaypoint("Install FishJump")
	end)
end

if not built then
	return warn("[InstallFishJump] Failed and rolled back: " .. tostring(buildErr))
end
print("[InstallFishJump] Installed:")
print("  patched " .. client:GetFullName() .. " (original backed up in ServerStorage.FishJumpBackup)")
print("  added   ReplicatedStorage.FishJump")
print("  tune    Workspace.SwimmingFish attributes JumpEnabled / JumpChance / JumpHeightScale (live)")
if not sourceMatches then
	warn("[InstallFishJump] Patched despite a source mismatch (ALLOW_SOURCE_MISMATCH).")
end
