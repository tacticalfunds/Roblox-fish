local function addMarker(id: number, name: string, meta)
	local marker = Instance.new("Configuration")
	marker.Name = "Fish" .. id
	marker:SetAttribute("FishId", id)
	marker:SetAttribute("FishName", name)
	marker:SetAttribute("Seed", id)
