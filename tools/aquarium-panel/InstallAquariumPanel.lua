		return
	end
	running = false
	for _, c in ipairs(connections) do
		c:Disconnect()
	end
	table.clear(connections)
	handOff(tank:shutdown())
	for id in pairs(markers) do
		removeMarker(id)
	end
	for i = #restore, 1, -1 do
		pcall(restore[i])
	end
	table.clear(restore)
	for i = #owned, 1, -1 do
		local inst = owned[i]
		if inst and inst.Parent then
			inst:Destroy()
		end
	end
	table.clear(owned)
	table.clear(prompts)
	countUi = nil
	root:SetAttribute("Running", false)
	root:SetAttribute("TankCount", nil)
	root:SetAttribute("TankCapacity", nil)
	root:SetAttribute("TankFull", nil)
	-- AquariumPanel
	root:SetAttribute("UpgradesAvailable", nil)
	root:SetAttribute("CapacityLevel", nil)
	root:SetAttribute("ReleaseRateLevel", nil)
	print("[AquariumCycle] stopped; catches go to the grinder")
end

