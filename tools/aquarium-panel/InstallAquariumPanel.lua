	local action = label(actionButton, "Action", 46, 7, PANEL_W - 70, 28)

	panel = {
		gui = gui,
		release = release,
		inputType = inputType,
		tank = tank,
		releaseKey = releaseKey,
		title = title,
		value = value,
		action = action,
		actionStroke = actionStroke,
