		end
		if #u.Values < 2 or #u.Costs ~= #u.Values - 1 or u.Values[1] ~= (u.StartValue or 1) or u.Values[2] ~= u.FirstValue then
			return false, "BoardUpgrades." .. id .. ": Values must start at StartValue (1), FirstValue with one Cost per step"
		end
