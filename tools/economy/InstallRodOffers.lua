		return nil, "noRod"
	end
	if self.byRod[rodKey] then
		return nil, "rodBusy"
	end
	if not self:validCaster(casterId) then
		return nil, "noCaster"
	end
	if type(price) ~= "number" or price < 1 or price ~= math.floor(price) then
		return nil, "badPrice"
	end
