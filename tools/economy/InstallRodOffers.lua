local function arc(from, to, dur, height, fn)
	local t = 0
	while t < dur do
		t += RunService.Heartbeat:Wait()
		local u = math.min(t / dur, 1)
		fn(from:Lerp(to, u) + Vector3.new(0, height * 4 * u * (1 - u), 0), u)
	end
end

