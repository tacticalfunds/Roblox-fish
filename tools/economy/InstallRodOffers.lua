	local offer: Offer = {
		id = self.nextId,
		rodKey = rodKey,
		casterId = casterId,
		fishName = fishName,
		tier = tier,
		variant = variant,
		price = price,
		expiresAt = now + self.timeout,
		status = "Open",
		reason = nil,
	}
	self.offers[offer.id] = offer
	self.byRod[rodKey] = offer.id
	return offer, nil
end

function Offers.get(self: Offers, id: any): Offer?
