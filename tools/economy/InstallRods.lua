	local okGui, gui = pcall(offerBillboard, p.fish, p.fishName, variant, price, p.chance)
	local okStand, stand =
		pcall(standAnchor, offer, standPos, workspace:GetServerTimeNow() + Config.Offer.TimeoutSeconds)
