	if not ok and reason ~= "notWaiting" then
		warn("[AquariumCycle] hook refused for rod " .. tostring(rodKey) .. ": " .. tostring(reason))
	end
	return ok
end

function M.land(rodKey: any): boolean
	if not running then
		return false
	end
