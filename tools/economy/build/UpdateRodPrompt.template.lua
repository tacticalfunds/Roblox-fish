--[[
	UpdateRodPrompt.lua - GENERATED by tools/economy/build/build_rod_prompt_update.py.
	Edit tools/economy sources and rebuild; don't edit this file.

	UPDATE for an existing rod-offers install (commit 8cb2554): rod fish are
	bought at the ROD STAND with a proximity prompt (custom panel: [E] + fish
	name + "Buy"; gamepad button / tap on touch) instead of the bottom-screen
	Buy/Pass panel. The label above the catch shows the real roll chance, the
	species and "$price". Money, prices and all server checks are unchanged,
	except that the buy range is now measured from the rod stand (10 studs +
	4 slack) and the caster dying cancels the offer (no charge).

	HOW TO RUN: stop Play, paste this whole file into the Command Bar (Edit
	mode), press Enter. It never runs automatically.

	Checks everything first and changes nothing if any check fails:
	  * Edit mode (not Play)
	  * the 8cb2554 install is present (ServerStorage.EconomyRodOffersBackup)
	    and this update isn't (ServerStorage.EconomyRodPromptBackup)
	  * no later economy milestone is installed
	  * every economy script is EXACTLY the 8cb2554 version (the 5 it changes
	    and the 6 it only reads)
	  * nothing named Workspace.EconomyBuyStands exists (the service creates
	    it during Play)
	Then, in one undo step ("Update RodPrompt"):
	  * backs up the 5 scripts to ServerStorage.EconomyRodPromptBackup
	    (Target ObjectValue + disabled Before/After copies)
	  * writes the new sources into RodFishingSystem, EconomyService,
	    EconomyService.Config, EconomyService.Offers and EconomyClient
	It does not touch ServerStorage.EconomyRodOffersBackup (the original
	uninstall chain). Undo with RollbackRodPrompt.lua (back to 8cb2554), then
	UninstallRodOffers.lua if you want the pre-economy game back.
]]

local ChangeHistoryService = game:GetService("ChangeHistoryService")
local ReplicatedStorage = game:GetService("ReplicatedStorage")
local RunService = game:GetService("RunService")
local ServerScriptService = game:GetService("ServerScriptService")
local ServerStorage = game:GetService("ServerStorage")
local StarterPlayer = game:GetService("StarterPlayer")

-- { key, old (8cb2554), new } scripts this update rewrites
local CHANGES = --[[@CHANGES]]
-- { key, source } scripts that must still be exactly the 8cb2554 version
local UNCHANGED = --[[@UNCHANGED]]

local TAG = "EconomyOwned"
local BASE_BACKUP = "EconomyRodOffersBackup"
local BACKUP = "EconomyRodPromptBackup"
local LATER = { "EconomySalesBackup", "EconomyAquariumBackup" }

local function fail(msg)
	warn("[UpdateRodPrompt] " .. msg .. " - nothing changed.")
end

local function normalize(s)
	s = s:gsub("\r", "")
	s = s:gsub("[ \t]+\n", "\n")
	s = s:gsub("%s+$", "")
	return s
end

------------------------------------------------------------ checks (read-only)

if RunService:IsRunning() then
	return fail("stop Play first (run this in Edit mode)")
end
local base = ServerStorage:FindFirstChild(BASE_BACKUP)
if not (base and base:GetAttribute(TAG) == true) then
	return fail("ServerStorage." .. BASE_BACKUP .. " not found: install InstallRodOffers.lua (8cb2554) first, or use the current InstallRodOffers.lua for a fresh install")
end
if ServerStorage:FindFirstChild(BACKUP) then
	return fail("ServerStorage." .. BACKUP .. " already exists (already updated? run RollbackRodPrompt.lua first)")
end
for _, name in ipairs(LATER) do
	if ServerStorage:FindFirstChild(name) then
		return fail("ServerStorage." .. name .. " exists: a later milestone is installed; roll it back first")
	end
end
if workspace:FindFirstChild("EconomyBuyStands") then
	return fail("Workspace.EconomyBuyStands exists; the economy creates it during Play - remove or rename yours first")
end

local function findScript(name)
	local found = {}
	for _, container in ipairs({ ServerScriptService, workspace }) do
		for _, d in ipairs(container:GetDescendants()) do
			if d.Name == name and d:IsA("Script") and not d:IsA("LocalScript") then
				table.insert(found, d)
			end
		end
	end
	if #found ~= 1 then
		return nil, string.format("expected exactly 1 Script named %s, found %d", name, #found)
	end
	return found[1]
end

local starterScripts = StarterPlayer:FindFirstChildOfClass("StarterPlayerScripts")
local service = ServerScriptService:FindFirstChild("EconomyService")

-- key -> the object it names (nil, reason if missing or not ours)
local function locate(key)
	if key == "RodFishingSystem" or key == "RodShopServer" then
		return findScript(key)
	end
	if key == "EconomyService" then
		if service and service:IsA("ModuleScript") and service:GetAttribute(TAG) == true then
			return service
		end
		return nil, "ServerScriptService.EconomyService (tagged ModuleScript) not found"
	end
	if key == "EconomyClient" then
		local c = starterScripts and starterScripts:FindFirstChild("EconomyClient")
		if c and c:IsA("LocalScript") and c:GetAttribute(TAG) == true then
			return c
		end
		return nil, "StarterPlayerScripts.EconomyClient (tagged LocalScript) not found"
	end
	local m = service and service:FindFirstChild(key)
	if m and m:IsA("ModuleScript") and m:GetAttribute(TAG) == true then
		return m
	end
	return nil, "EconomyService." .. key .. " (tagged ModuleScript) not found"
end

if not (ReplicatedStorage:FindFirstChild("Economy") and ReplicatedStorage.Economy:GetAttribute(TAG) == true) then
	return fail("ReplicatedStorage.Economy (tagged) not found")
end
for _, entry in ipairs(UNCHANGED) do
	local target, why = locate(entry.key)
	if not target then
		return fail(why)
	end
	if normalize(target.Source) ~= normalize(entry.source) then
		return fail(target:GetFullName() .. " is not the 8cb2554 version (send the current source)")
	end
end
local changes = {}
for _, entry in ipairs(CHANGES) do
	local target, why = locate(entry.key)
	if not target then
		return fail(why)
	end
	if normalize(target.Source) ~= normalize(entry.old) then
		return fail(target:GetFullName() .. " is not the 8cb2554 version (send the current source)")
	end
	table.insert(changes, { target = target, key = entry.key, new = entry.new })
end

------------------------------------------------------------ update

local recording
local ok = pcall(function()
	recording = ChangeHistoryService:TryBeginRecording("Update RodPrompt")
end)
if not ok or not recording then
	recording = nil
	pcall(function()
		ChangeHistoryService:SetWaypoint("Before Update RodPrompt")
	end)
end

-- a disabled, childless copy holding one source
local function copyOf(target, name, source)
	local c = Instance.new(target.ClassName)
	c.Name = name
	c.Source = source
	if c:IsA("Script") or c:IsA("LocalScript") then
		c.Enabled = false
	end
	return c
end

local originals = {}
local backup
local built, buildErr = pcall(function()
	backup = Instance.new("Folder")
	backup.Name = BACKUP
	backup:SetAttribute(TAG, true)
	backup:SetAttribute("From", "8cb2554")
	for i, change in ipairs(changes) do
		originals[i] = change.target.Source
		local entry = Instance.new("Folder")
		entry.Name = string.format("%02d_%s", i, change.key)
		entry:SetAttribute("TargetPath", change.target:GetFullName())
		local targetValue = Instance.new("ObjectValue")
		targetValue.Name = "Target"
		targetValue.Value = change.target
		targetValue.Parent = entry
		copyOf(change.target, "Before", originals[i]).Parent = entry
		change.target.Source = change.new
		copyOf(change.target, "After", change.target.Source).Parent = entry
		entry.Parent = backup
	end
	backup.Parent = ServerStorage
end)

if not built then
	for i, change in ipairs(changes) do
		if originals[i] then
			pcall(function()
				change.target.Source = originals[i]
			end)
		end
	end
	if backup then
		pcall(function()
			backup:Destroy()
		end)
	end
end

if recording then
	ChangeHistoryService:FinishRecording(
		recording,
		if built then Enum.FinishRecordingOperation.Commit else Enum.FinishRecordingOperation.Cancel
	)
elseif built then
	pcall(function()
		ChangeHistoryService:SetWaypoint("Update RodPrompt")
	end)
end

if not built then
	return warn("[UpdateRodPrompt] Failed and rolled back: " .. tostring(buildErr))
end
print("[UpdateRodPrompt] Updated (rod-stand buy prompt):")
for _, change in ipairs(changes) do
	print("  updated " .. change.target:GetFullName())
end
print("  backup  ServerStorage." .. BACKUP .. " (RollbackRodPrompt.lua restores 8cb2554)")
