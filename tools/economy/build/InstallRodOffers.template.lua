--[[
	InstallRodOffers.lua - GENERATED by tools/economy/build/build_rod_offers_installer.py.
	Edit tools/economy sources and rebuild; don't edit this file.

	Rod-fish Buy/Pass + the Money service (leaderstats.Money, saved).
	REQUIRES the aquarium to be installed (and enabled) first.
	HOW TO RUN: stop Play, paste this whole file into the Command Bar (Edit
	mode), press Enter. It never runs automatically.

	Checks everything first and changes nothing if any check fails:
	  * none of its own objects exist yet
	  * no other script creates leaderstats (no parallel money)
	  * the aquarium is installed (ServerScriptService.AquariumCycleServer,
	    ReplicatedStorage.AquariumCycle)
	  * exactly one Script each named RodFishingSystem and RodShopServer
	    (ServerScriptService / Workspace), each matching the live source Astra
	    supplied on 2026-09-28
	Then, in one undo step ("Install RodOffers"):
	  * backs up both scripts to ServerStorage.EconomyRodOffersBackup
	    (Target ObjectValue + disabled Before/After copies)
	  * patches RodFishingSystem (Buy/Pass offers) and RodShopServer (charges
	    through EconomyService; shop stays closed until rods do something)
	  * adds ReplicatedStorage.Economy (RodOffersEnabled = true; Notice,
	    OfferAction, Offers), ServerScriptService.EconomyService (+ core
	    modules), ServerScriptService.EconomyBoot,
	    StarterPlayer.StarterPlayerScripts.EconomyClient
	Added objects carry EconomyOwned = true. UninstallRodOffers.lua reverses it.
]]

local ALLOW_SOURCE_MISMATCH = false -- never set true without Astra re-reviewing the diff

local ChangeHistoryService = game:GetService("ChangeHistoryService")
local ReplicatedStorage = game:GetService("ReplicatedStorage")
local ServerScriptService = game:GetService("ServerScriptService")
local ServerStorage = game:GetService("ServerStorage")
local StarterPlayer = game:GetService("StarterPlayer")

-- { name, base, patched }
local SCRIPTS = --[[@SCRIPTS]]
local SERVICE = --[[@SERVICE]]
-- { name, source } children of EconomyService
local CORE = --[[@CORE]]
local BOOT = --[[@BOOT]]
local CLIENT = --[[@CLIENT]]

local TAG = "EconomyOwned"
local BACKUP = "EconomyRodOffersBackup"

local function fail(msg)
	warn("[InstallRodOffers] " .. msg .. " - nothing changed.")
end

local function normalize(s)
	s = s:gsub("\r", "")
	s = s:gsub("[ \t]+\n", "\n")
	s = s:gsub("%s+$", "")
	return s
end

------------------------------------------------------------ checks (read-only)

local starterScripts = StarterPlayer:FindFirstChildOfClass("StarterPlayerScripts")
if not starterScripts then
	return fail("StarterPlayer.StarterPlayerScripts not found")
end

-- Dense { parent, name } list: every slot is checked (a table of
-- FindFirstChild results would stop ipairs at the first missing one).
local OWN = {
	{ ReplicatedStorage, "Economy" },
	{ ServerScriptService, "EconomyService" },
	{ ServerScriptService, "EconomyBoot" },
	{ starterScripts, "EconomyClient" },
	{ ServerStorage, BACKUP },
}
for _, slot in ipairs(OWN) do
	local existing = slot[1]:FindFirstChild(slot[2])
	if existing then
		return fail(existing:GetFullName() .. " already exists (partial or earlier install? run UninstallRodOffers.lua, or remove it by hand if it isn't ours)")
	end
end

-- No parallel money: nothing else may create leaderstats.
for _, container in ipairs({ ServerScriptService, workspace, ReplicatedStorage, ServerStorage, StarterPlayer }) do
	for _, d in ipairs(container:GetDescendants()) do
		if d:IsA("LuaSourceContainer") and d.Name ~= "RodShopServer" then
			local ok, src = pcall(function()
				return d.Source
			end)
			if ok and type(src) == "string" and (src:find('"leaderstats"', 1, true) or src:find("'leaderstats'", 1, true)) and not d:IsDescendantOf(ServerStorage) then
				return fail(d:GetFullName() .. " mentions leaderstats; review it before adding the Money service")
			end
		end
	end
end

if not (ServerScriptService:FindFirstChild("AquariumCycleServer") and ReplicatedStorage:FindFirstChild("AquariumCycle")) then
	return fail("the aquarium is not installed (bought fish go to the aquarium)")
end
if ReplicatedStorage.AquariumCycle:GetAttribute("Enabled") ~= true then
	warn("[InstallRodOffers] note: ReplicatedStorage.AquariumCycle.Enabled is not true - rods will stay paused until it is")
end

local function findScript(name)
	local found = {}
	for _, container in ipairs({ ServerScriptService, workspace }) do
		for _, d in ipairs(container:GetDescendants()) do
			if d.Name == name and d:IsA("Script") and not d:IsA("LocalScript") then
				table.insert(found, d)
			end
		end
	end
	return found
end

local changes = {}
for _, entry in ipairs(SCRIPTS) do
	local found = findScript(entry.name)
	if #found ~= 1 then
		return fail(string.format("expected exactly 1 Script named %s, found %d", entry.name, #found))
	end
	local target = found[1]
	if normalize(target.Source) ~= normalize(entry.base) and not ALLOW_SOURCE_MISMATCH then
		return fail(target:GetFullName() .. " differs from the live source this patch was built on (send the current source)")
	end
	table.insert(changes, { target = target, after = entry.patched, label = entry.name })
end

------------------------------------------------------------ install

local recording
local ok = pcall(function()
	recording = ChangeHistoryService:TryBeginRecording("Install RodOffers")
end)
if not ok or not recording then
	recording = nil
	pcall(function()
		ChangeHistoryService:SetWaypoint("Before Install RodOffers")
	end)
end

local originals = {}
local created = {}

local function copyOf(source, name)
	local c = source:Clone()
	c.Name = name
	if c:IsA("Script") or c:IsA("LocalScript") then
		c.Enabled = false
	end
	return c
end

local function make(className, name, parent, source)
	local inst = Instance.new(className)
	inst.Name = name
	if source then
		inst.Source = source
	end
	inst:SetAttribute(TAG, true)
	table.insert(created, inst)
	inst.Parent = parent
	return inst
end

local built, buildErr = pcall(function()
	local backup = Instance.new("Folder")
	backup.Name = BACKUP
	backup:SetAttribute(TAG, true)
	table.insert(created, backup)
	for i, change in ipairs(changes) do
		originals[i] = change.target.Source
		local entry = Instance.new("Folder")
		entry.Name = string.format("%02d_%s", i, change.label)
		entry:SetAttribute("TargetPath", change.target:GetFullName())
		local targetValue = Instance.new("ObjectValue")
		targetValue.Name = "Target"
		targetValue.Value = change.target
		targetValue.Parent = entry
		copyOf(change.target, "Before").Parent = entry
		change.target.Source = change.after
		copyOf(change.target, "After").Parent = entry
		entry.Parent = backup
	end
	backup.Parent = ServerStorage

	-- replicated root (remotes + offers the client reads)
	local root = Instance.new("Folder")
	root.Name = "Economy"
	root:SetAttribute(TAG, true)
	root:SetAttribute("RodOffersEnabled", true)
	make("RemoteEvent", "Notice", root)
	make("RemoteFunction", "OfferAction", root)
	make("Folder", "Offers", root)
	table.insert(created, root)
	root.Parent = ReplicatedStorage

	local service = Instance.new("ModuleScript")
	service.Name = "EconomyService"
	service.Source = SERVICE
	service:SetAttribute(TAG, true)
	for _, m in ipairs(CORE) do
		make("ModuleScript", m.name, service, m.source)
	end
	table.insert(created, service)
	service.Parent = ServerScriptService

	make("Script", "EconomyBoot", ServerScriptService, BOOT)
	make("LocalScript", "EconomyClient", starterScripts, CLIENT)
end)

if not built then
	for i, change in ipairs(changes) do
		if originals[i] then
			pcall(function()
				change.target.Source = originals[i]
			end)
		end
	end
	for i = #created, 1, -1 do
		pcall(function()
			created[i]:Destroy()
		end)
	end
end

if recording then
	ChangeHistoryService:FinishRecording(
		recording,
		if built then Enum.FinishRecordingOperation.Commit else Enum.FinishRecordingOperation.Cancel
	)
elseif built then
	pcall(function()
		ChangeHistoryService:SetWaypoint("Install RodOffers")
	end)
end

if not built then
	return warn("[InstallRodOffers] Failed and rolled back: " .. tostring(buildErr))
end
print("[InstallRodOffers] Installed:")
for _, change in ipairs(changes) do
	print("  patched " .. change.target:GetFullName())
end
print("  added   ReplicatedStorage.Economy, ServerScriptService.EconomyService (+core), EconomyBoot, StarterPlayerScripts.EconomyClient")
print("  money   leaderstats.Money (DataStore --[[@STORE]]); new players get the one-time starting grant")
print("  note    Studio play tests need 'Enable Studio Access to API Services' to persist; otherwise a temporary in-memory store is used")
