		return false, "badArgs"
	end
	local rod, err = ownedRod(self, owner, rodId)
	if not rod then
		return false, err
	end
	if rod.phase ~= "Waiting" then
		return false, "notWaiting"
	end
	if now < rod.castAt + self.config.BiteSeconds then
		return false, "tooSoon"
