	if not fish or fish.location ~= "River" then
		return false, "fishUnavailable"
	end
	fish.location = "Hooked"
	fish.rodId = rodId
	rod.phase = "Hooked"
	rod.hookedAt = now
	rod.fishId = fishId
	return true, nil
