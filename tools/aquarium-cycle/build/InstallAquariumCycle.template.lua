--[[
	InstallAquariumCycle.lua - GENERATED by tools/aquarium-cycle/build/build_installer.py.
	Edit the sources under tools/aquarium-cycle and rebuild; don't edit this file.

	Opt-in Studio installer for the dock rod -> aquarium -> river cycle.
	HOW TO RUN: stop Play, then paste this whole file into the Command Bar
	(Edit mode) and press Enter. It never runs automatically.

	It first checks everything and changes nothing if any check fails:
	  * none of its own objects already exist (run the uninstaller first)
	  * exactly one Script named RodFishingSystem under ServerScriptService,
	    whose source matches the reviewed original embedded below
	  * Workspace.FishTank.BaseWater (BasePart), Workspace.SwimmingFish with
	    numeric MinX/MaxX/MinZ/MaxZ/SurfaceY, ReplicatedStorage.SwimTemplates
	    and ReplicatedStorage.FishModels

	Then, in one undo step ("Install AquariumCycle"):
	  1. backs up RodFishingSystem to ServerStorage.AquariumCycleBackup
	     (disabled copies of the original and the patched script)
	  2. replaces RodFishingSystem.Source with the patched version
	  3. adds ReplicatedStorage.AquariumCycle (pure modules + Bindings
	     ObjectValues, attribute Enabled)
	  4. adds ServerScriptService.AquariumCycleServer and .AquariumEconomy
	  5. adds StarterPlayer.StarterPlayerScripts.AquariumTankClient
	Every added object carries the attribute AquariumCycleOwned = true; the
	uninstaller removes only those and restores the original source.

	Kill switch without uninstalling: untick the "Enabled" attribute on
	ReplicatedStorage.AquariumCycle. Rod catches then go to the grinder
	exactly as before (also mid-play: tank fish are put back in the river).
]]

-- Set true only if Astra has reviewed a difference between the live
-- RodFishingSystem and the embedded original and wants to patch anyway.
local ALLOW_SOURCE_MISMATCH = false
-- Installed switched on so a Play test exercises it; untick to disable.
local ENABLE_ON_INSTALL = true

local ChangeHistoryService = game:GetService("ChangeHistoryService")
local ReplicatedStorage = game:GetService("ReplicatedStorage")
local ServerScriptService = game:GetService("ServerScriptService")
local ServerStorage = game:GetService("ServerStorage")
local StarterPlayer = game:GetService("StarterPlayer")

local ORIGINAL = --[[@ORIGINAL]]
local PATCHED = --[[@PATCHED]]
local SHARED = --[[@SHARED]]
local SERVER = --[[@SERVER]]
local ECONOMY = --[[@ECONOMY]]
local CLIENT = --[[@CLIENT]]

local TAG = "AquariumCycleOwned"

local function fail(msg)
	warn("[InstallAquariumCycle] " .. msg .. " - nothing changed.")
end

local function normalize(s)
	s = s:gsub("\r", "")
	s = s:gsub("[ \t]+\n", "\n")
	s = s:gsub("%s+$", "")
	return s
end

------------------------------------------------------------ checks (read-only)

local starterScripts = StarterPlayer:FindFirstChildOfClass("StarterPlayerScripts")
if not starterScripts then
	return fail("StarterPlayer.StarterPlayerScripts not found")
end
for _, existing in ipairs({
	ReplicatedStorage:FindFirstChild("AquariumCycle"),
	ServerScriptService:FindFirstChild("AquariumCycleServer"),
	ServerScriptService:FindFirstChild("AquariumEconomy"),
	starterScripts:FindFirstChild("AquariumTankClient"),
	ServerStorage:FindFirstChild("AquariumCycleBackup"),
}) do
	if existing then
		return fail(existing:GetFullName() .. " already exists (already installed? run UninstallAquariumCycle.lua first)")
	end
end

local rodScripts = {}
for _, d in ipairs(ServerScriptService:GetDescendants()) do
	if d.Name == "RodFishingSystem" and d:IsA("Script") then
		table.insert(rodScripts, d)
	end
end
if #rodScripts ~= 1 then
	return fail(string.format("expected exactly 1 Script named RodFishingSystem in ServerScriptService, found %d", #rodScripts))
end
local rodScript = rodScripts[1]
local sourceMatches = normalize(rodScript.Source) == normalize(ORIGINAL)
if not sourceMatches and not ALLOW_SOURCE_MISMATCH then
	return fail(
		rodScript:GetFullName()
			.. " source differs from the reviewed original (tools/aquarium-cycle/studio/RodFishingSystem.original.lua)."
			.. " Send the current source for a re-patch, or set ALLOW_SOURCE_MISMATCH after review"
	)
end

local fishTank = workspace:FindFirstChild("FishTank")
local baseWater = fishTank and fishTank:FindFirstChild("BaseWater")
if not (baseWater and baseWater:IsA("BasePart")) then
	return fail("Workspace.FishTank.BaseWater (BasePart) not found")
end
local river = workspace:FindFirstChild("SwimmingFish")
if not river then
	return fail("Workspace.SwimmingFish not found")
end
for _, attr in ipairs({ "MinX", "MaxX", "MinZ", "MaxZ", "SurfaceY" }) do
	if type(river:GetAttribute(attr)) ~= "number" then
		return fail("Workspace.SwimmingFish attribute " .. attr .. " missing or not a number")
	end
end
local swimTemplates = ReplicatedStorage:FindFirstChild("SwimTemplates")
local fishModels = ReplicatedStorage:FindFirstChild("FishModels")
if not (swimTemplates and fishModels) then
	return fail("ReplicatedStorage.SwimTemplates / FishModels not found")
end

-- Optional: the fish loader beside the tank (release swim target).
local loader = workspace:FindFirstChild("FishLoader")
if loader and not loader:IsA("PVInstance") then
	loader = nil
end

-- Optional: the placeholder count UI, Workspace.Model.Road.ProximityPrompt
-- with BillboardGui.TextLabel "Fish available" and BillboardGui.Amount. Several
-- Workspace children may be called "Model", so require exactly one match.
local countPrompts = {}
for _, m in ipairs(workspace:GetChildren()) do
	if m.Name == "Model" then
		local road = m:FindFirstChild("Road")
		local prompt = road and road:FindFirstChild("ProximityPrompt")
		local gui = prompt and prompt:FindFirstChild("BillboardGui")
		local title = gui and gui:FindFirstChild("TextLabel")
		local amount = gui and gui:FindFirstChild("Amount")
		if
			prompt
			and prompt:IsA("ProximityPrompt")
			and title
			and title:IsA("TextLabel")
			and title.Text == "Fish available"
			and amount
			and amount:IsA("TextLabel")
		then
			table.insert(countPrompts, prompt)
		end
	end
end
local countPrompt = if #countPrompts == 1 then countPrompts[1] else nil

local rodCount = 0
for _, m in ipairs(workspace:GetChildren()) do
	if m.Name == "FishingRod1" and m:IsA("Model") then
		rodCount += 1
	end
end

------------------------------------------------------------ install

local recording
local ok = pcall(function()
	recording = ChangeHistoryService:TryBeginRecording("Install AquariumCycle")
end)
if not ok or not recording then
	recording = nil
	pcall(function()
		ChangeHistoryService:SetWaypoint("Before Install AquariumCycle")
	end)
end

local originalSource = rodScript.Source
local created = {}

local function tagged(inst)
	inst:SetAttribute(TAG, true)
	table.insert(created, inst)
	return inst
end

local function moduleScript(name, source, parent)
	local m = Instance.new("ModuleScript")
	m.Name = name
	m.Source = source
	m.Parent = parent
	return m
end

local built, buildErr = pcall(function()
	-- 1) backup
	local backup = tagged(Instance.new("Folder"))
	backup.Name = "AquariumCycleBackup"
	backup:SetAttribute("OriginalPath", rodScript:GetFullName())
	backup:SetAttribute("SourceMatchedReviewedOriginal", sourceMatches)
	local originalCopy = rodScript:Clone()
	originalCopy.Name = "RodFishingSystem_original"
	originalCopy.Enabled = false
	originalCopy.Parent = backup
	local target = Instance.new("ObjectValue")
	target.Name = "Target"
	target.Value = rodScript
	target.Parent = backup
	backup.Parent = ServerStorage

	-- 2) patch
	rodScript.Source = PATCHED
	local patchedCopy = rodScript:Clone()
	patchedCopy.Name = "RodFishingSystem_patched"
	patchedCopy.Enabled = false
	patchedCopy.Parent = backup

	-- 3) shared modules + bindings
	local folder = tagged(Instance.new("Folder"))
	folder.Name = "AquariumCycle"
	for _, mod in ipairs(SHARED) do
		moduleScript(mod.name, mod.source, folder)
	end
	local bindings = Instance.new("Folder")
	bindings.Name = "Bindings"
	local function bind(name, value)
		if value then
			local v = Instance.new("ObjectValue")
			v.Name = name
			v.Value = value
			v.Parent = bindings
		end
	end
	bind("TankWater", baseWater)
	bind("River", river)
	bind("SwimTemplates", swimTemplates)
	bind("FishModels", fishModels)
	bind("Loader", loader)
	bind("CountPrompt", countPrompt)
	bindings.Parent = folder
	folder:SetAttribute("Enabled", ENABLE_ON_INSTALL)
	folder:SetAttribute("InstallerVersion", 1)
	folder.Parent = ReplicatedStorage

	-- 4) server modules
	tagged(moduleScript("AquariumCycleServer", SERVER, ServerScriptService))
	tagged(moduleScript("AquariumEconomy", ECONOMY, ServerScriptService))

	-- 5) client visuals
	local client = tagged(Instance.new("LocalScript"))
	client.Name = "AquariumTankClient"
	client.Source = CLIENT
	client.Parent = starterScripts
end)

if not built then
	-- Undo by hand too, in case the history recording isn't available.
	pcall(function()
		rodScript.Source = originalSource
	end)
	for i = #created, 1, -1 do
		pcall(function()
			created[i]:Destroy()
		end)
	end
end

if recording then
	ChangeHistoryService:FinishRecording(
		recording,
		if built then Enum.FinishRecordingOperation.Commit else Enum.FinishRecordingOperation.Cancel
	)
elseif built then
	pcall(function()
		ChangeHistoryService:SetWaypoint("Install AquariumCycle")
	end)
end

if not built then
	return warn("[InstallAquariumCycle] Failed and rolled back: " .. tostring(buildErr))
end

print("[InstallAquariumCycle] Installed:")
print("  patched  " .. rodScript:GetFullName() .. " (original backed up in ServerStorage.AquariumCycleBackup)")
print("  added    ReplicatedStorage.AquariumCycle (" .. #SHARED .. " modules, Bindings, Enabled=" .. tostring(ENABLE_ON_INSTALL) .. ")")
print("  added    ServerScriptService.AquariumCycleServer, ServerScriptService.AquariumEconomy")
print("  added    StarterPlayer.StarterPlayerScripts.AquariumTankClient")
print("  bindings TankWater=" .. baseWater:GetFullName() .. ", River=" .. river:GetFullName())
print("           Loader=" .. (if loader then loader:GetFullName() else "(none: fish leave over the tank rim)"))
print(
	"           CountPrompt="
		.. (if countPrompt then countPrompt:GetFullName() else string.format("(not bound: %d matches; own counter used)", #countPrompts))
)
print(string.format("  rods     %d FishingRod1 model(s) in Workspace (RodFishingSystem finds them itself)", rodCount))
if not sourceMatches then
	warn("[InstallAquariumCycle] Patched despite a source mismatch (ALLOW_SOURCE_MISMATCH).")
end
print("  upgrades unavailable until ServerScriptService.AquariumEconomy returns a currency binding")
