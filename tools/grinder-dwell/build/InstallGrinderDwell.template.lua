--[[
	InstallGrinderDwell.lua - GENERATED by tools/grinder-dwell/build/build_installer.py.
	Edit tools/grinder-dwell sources and rebuild; don't edit this file.

	Opt-in Studio installer: fish arriving at the grinder rest on the rollers,
	tumbling for about a second, before being pulled in. Applies to net catches
	(FishSwimClient visuals + NetLiftScript timing) and to rod catches that go
	to the grinder (RodFishingSystem fallback). Aquarium routing is unchanged.
	Install this LAST: it accepts whichever reviewed versions are live, but the
	other installers refuse scripts it has patched.
	HOW TO RUN: stop Play, paste this whole file into the Command Bar (Edit
	mode), press Enter. It never runs automatically.

	Checks first, changes nothing on failure:
	  * ServerStorage.GrinderDwellBackup and ReplicatedStorage.GrinderDwell don't exist
	  * exactly one FishSwimClient (LocalScript), NetLiftScript and
	    RodFishingSystem (Scripts), each matching one of its reviewed versions
	In one undo step ("Install GrinderDwell") it backs all three up to
	ServerStorage.GrinderDwellBackup (Target + disabled Before/After copies),
	patches them and adds ReplicatedStorage.GrinderDwell (tagged
	GrinderDwellOwned). UninstallGrinderDwell.lua reverses it.
]]

local ChangeHistoryService = game:GetService("ChangeHistoryService")
local ReplicatedFirst = game:GetService("ReplicatedFirst")
local ReplicatedStorage = game:GetService("ReplicatedStorage")
local ServerScriptService = game:GetService("ServerScriptService")
local ServerStorage = game:GetService("ServerStorage")
local StarterGui = game:GetService("StarterGui")
local StarterPlayer = game:GetService("StarterPlayer")

-- { name, localScript, candidates = { { label, base, patched } } }
local TARGETS = --[[@TARGETS]]
local MODULE = --[[@MODULE]]

local TAG = "GrinderDwellOwned"

local function fail(msg)
	warn("[InstallGrinderDwell] " .. msg .. " - nothing changed.")
end

local function normalize(s)
	s = s:gsub("\r", "")
	s = s:gsub("[ \t]+\n", "\n")
	s = s:gsub("%s+$", "")
	return s
end

if ServerStorage:FindFirstChild("GrinderDwellBackup") or ReplicatedStorage:FindFirstChild("GrinderDwell") then
	return fail("already installed (run UninstallGrinderDwell.lua first)")
end

local function find(name, isLocal)
	local containers = if isLocal
		then { StarterPlayer, StarterGui, ReplicatedFirst }
		else { ServerScriptService, workspace }
	local found = {}
	for _, container in ipairs(containers) do
		for _, d in ipairs(container:GetDescendants()) do
			if d.Name == name and d:IsA("Script") and (d:IsA("LocalScript") == isLocal) then
				table.insert(found, d)
			end
		end
	end
	return found
end

local changes = {}
for _, t in ipairs(TARGETS) do
	local found = find(t.name, t.localScript)
	if #found ~= 1 then
		return fail(string.format("expected exactly 1 %s named %s, found %d", if t.localScript then "LocalScript" else "Script", t.name, #found))
	end
	local target = found[1]
	local current = normalize(target.Source)
	local match
	for _, c in ipairs(t.candidates) do
		if current == normalize(c.base) then
			match = c
			break
		end
	end
	if not match then
		return fail(target:GetFullName() .. " doesn't match any reviewed version (already patched?)")
	end
	table.insert(changes, { target = target, after = match.patched, label = t.name .. " (" .. match.label .. ")" })
end

local recording
local ok = pcall(function()
	recording = ChangeHistoryService:TryBeginRecording("Install GrinderDwell")
end)
if not ok or not recording then
	recording = nil
	pcall(function()
		ChangeHistoryService:SetWaypoint("Before Install GrinderDwell")
	end)
end

local originals, backup, module = {}, nil, nil
local built, buildErr = pcall(function()
	backup = Instance.new("Folder")
	backup.Name = "GrinderDwellBackup"
	backup:SetAttribute(TAG, true)
	for i, change in ipairs(changes) do
		originals[i] = change.target.Source
		local entry = Instance.new("Folder")
		entry.Name = string.format("%02d_%s", i, change.target.Name)
		local targetValue = Instance.new("ObjectValue")
		targetValue.Name = "Target"
		targetValue.Value = change.target
		targetValue.Parent = entry
		local before = change.target:Clone()
		before.Name = "Before"
		before.Enabled = false
		before.Parent = entry
		change.target.Source = change.after
		local after = change.target:Clone()
		after.Name = "After"
		after.Enabled = false
		after.Parent = entry
		entry.Parent = backup
	end
	backup.Parent = ServerStorage
	module = Instance.new("ModuleScript")
	module.Name = "GrinderDwell"
	module.Source = MODULE
	module:SetAttribute(TAG, true)
	module.Parent = ReplicatedStorage
end)

if not built then
	for i, change in ipairs(changes) do
		if originals[i] then
			pcall(function()
				change.target.Source = originals[i]
			end)
		end
	end
	for _, inst in ipairs({ backup, module }) do
		pcall(function()
			inst:Destroy()
		end)
	end
end

if recording then
	ChangeHistoryService:FinishRecording(
		recording,
		if built then Enum.FinishRecordingOperation.Commit else Enum.FinishRecordingOperation.Cancel
	)
elseif built then
	pcall(function()
		ChangeHistoryService:SetWaypoint("Install GrinderDwell")
	end)
end

if not built then
	return warn("[InstallGrinderDwell] Failed and rolled back: " .. tostring(buildErr))
end
print("[InstallGrinderDwell] Installed:")
for _, change in ipairs(changes) do
	print("  patched " .. change.target:GetFullName() .. " from " .. change.label)
end
print("  added   ReplicatedStorage.GrinderDwell (tune Dwell / OffsetY there)")
